CREATE DATABASE ORDER_DB;

USE ORDER_DB;

CREATE TABLE CUSTOMER (
		CUST_ID INT,
        CUST_NAME VARCHAR(250),
        CUST_ADDRESS VARCHAR(100)
        );

CREATE TABLE ORDER_1 (
		ORDER_ID INT,
        CUST_ID INT,
        ORDER_PRODUCT VARCHAR(100),
        ORDER_PRICE INT
        );
        
