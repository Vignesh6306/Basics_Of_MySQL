SELECT C.CUST_ID,
	   C.CUST_NAME,
       O.ORDER_PRODUCT,
       O.ORDER_PRICE,
       C.CUST_ADDRESS
FROM CUSTOMER AS C
INNER JOIN ORDER_1 AS O
ON C.CUST_ID = O.CUST_ID;


SELECT 
	   C.CUST_NAME,
       O.ORDER_PRODUCT,
       O.ORDER_PRICE
FROM CUSTOMER AS C
LEFT JOIN ORDER_1 AS O
ON C.CUST_ID = O.CUST_ID;


SELECT C.CUST_ID,
	   C.CUST_NAME,
       O.ORDER_PRODUCT,
       O.ORDER_PRICE,
       C.CUST_ADDRESS
FROM CUSTOMER AS C
RIGHT JOIN ORDER_1 AS O
ON C.CUST_ID = O.CUST_ID;

SELECT C.CUST_ID,
	   C.CUST_NAME,
       O.ORDER_PRODUCT,
       O.ORDER_PRICE,
       C.CUST_ADDRESS
FROM CUSTOMER AS C
CROSS JOIN ORDER_1 AS O
ON C.CUST_ID = O.CUST_ID;

        
     
      
		
        