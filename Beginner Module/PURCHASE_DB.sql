CREATE DATABASE PURCHASE_DB;

USE PURCHASE_DB;

CREATE TABLE PURCHASE_1(
		NAME VARCHAR(250),
        PURCHASE INT,
        COUNTRY VARCHAR(100),
        PRODUCT VARCHAR(250),
        AGE INT
        );
        
