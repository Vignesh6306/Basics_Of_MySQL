SELECT * FROM PURCHASE_1 
ORDER BY PURCHASE ASC;

SELECT COUNT(PRODUCT) AS TOTAL_PRODUCT
FROM PURCHASE_1 
GROUP BY PRODUCT;

SELECT COUNTRY, SUM(PURCHASE) AS TOTAL_PURCHASE
FROM PURCHASE_1
GROUP BY COUNTRY
ORDER BY TOTAL_PURCHASE;

SELECT MAX(AGE) AS MAX_AGE
FROM PURCHASE_1
GROUP BY AGE;

SELECT PRODUCT, SUM(PURCHASE) AS SUM_PURCHASE
FROM PURCHASE_1
GROUP BY PRODUCT
ORDER BY SUM_PURCHASE;

		