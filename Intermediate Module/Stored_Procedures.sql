CREATE TABLE STUDENT(
		STUDENT_ID INT NOT NULL AUTO_INCREMENT,
        STUDENT_NAME VARCHAR(100),
        STUDENT_DEPT VARCHAR(10),
        STUDENT_AGE INT,
        PRIMARY KEY(STUDENT_ID)
        );
        
