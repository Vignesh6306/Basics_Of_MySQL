DELIMITER //
CREATE PROCEDURE STUDENT_INFO(
	IN	S_NAME VARCHAR(100),
    IN  S_AGE INT
    ) 
BEGIN
SELECT * FROM STUDENT
WHERE STUDENT_NAME = S_NAME
AND STUDENT_AGE = S_AGE;
END //
DELIMITER ;

