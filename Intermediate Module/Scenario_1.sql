CREATE DATABASE COLLEGE_REGISTRATION;

USE COLLEGE_REGISTRATION;

CREATE TABLE DEPARTMENT(
		DEPT_ID INT,
        DEPT_NAME VARCHAR(200),
        DEPT_LOCATION VARCHAR(200)
        );
        
CREATE TABLE STUDENT(
		STUDENT_ID INT,
        STUDENT_NAME VARCHAR(200),
        STUDENT_YOJ YEAR,
        DEPT_ID INT
        );
        
CREATE TABLE COURSE(
			COURSE_ID INT,
			COURSE_NAME VARCHAR(10),
            COURSE_CREDIT INT,
            DEPT_ID INT 
            );
            
