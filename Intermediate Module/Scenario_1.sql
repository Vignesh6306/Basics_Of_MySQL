CREATE VIEW COURSE_DETAILS AS 
SELECT COURSE_NAME,
	   COURSE_CREDIT
FROM COURSE; 

SELECT S.STUDENT_NAME,
	   C.COURSE_NAME,
       C.COURSE_CREDIT
FROM STUDENT AS S
INNER JOIN COURSE AS C
ON S.DEPT_ID = C.DEPT_ID
ORDER BY COURSE_CREDIT;       
        
SELECT  S.STUDENT_ID,
		S.STUDENT_NAME,
		D.DEPT_ID,
        D.DEPT_NAME,
        D.DEPT_LOCATION
FROM STUDENT AS S
INNER JOIN DEPARTMENT AS D
ON S.DEPT_ID = D.DEPT_ID

         

  

        


		

